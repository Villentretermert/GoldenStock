// Verify the authored prototype locally, without network access or user files.
const {createRequire}=require('module');
const fs=require('fs');
const path=require('path');
const req=createRequire(path.join(process.env.GS_NODE_MODULES,'playwright','package.json'));
const {chromium}=req('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1280,height:1000}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',r=>r.abort());
 const html=fs.readFileSync('design/goldenstock-prototype.html','utf8');
 await page.setContent('<!doctype html><html><head><meta charset="UTF-8"><style>body{margin:20px;color-scheme:light}</style></head><body>'+html+'</body></html>');
 await page.locator('[data-page="models"]').first().click();
 await page.locator('[data-action="build"]').click();
 if(!(await page.locator('#gs-model-state').innerText()).includes('Blocked'))throw Error('Unreviewed build must block');
 await page.locator('[data-page="review"]').first().click();
 await page.locator('[data-action="confirm"]').click();
 await page.locator('[data-page="models"]').first().click();
 await page.locator('[data-action="build"]').click();
 if(!(await page.locator('#gs-model-state').innerText()).includes('ready'))throw Error('Reviewed flow failed');
 await page.locator('[data-action="share"]').click();
 await page.locator('[data-action="publish"]').click();
 if(!(await page.locator('main').innerText()).includes('Shared with Pilot Fund'))throw Error('Sharing failed');
 await page.locator('[data-action="export-PDF"]').click();
 if(!(await page.locator('#gs-message').innerText()).includes('Real export is not implemented'))throw Error('Export honesty failed');
 await page.locator('[data-page="upload"]').first().click();
 await page.locator('[data-action="upload"]').click();
 if(!(await page.locator('#gs-upload-state').innerText()).includes('Choose'))throw Error('Missing file validation');
 await page.locator('#gs-file').setInputFiles({name:'demo.pdf',mimeType:'application/pdf',buffer:Buffer.from('synthetic')});
 await page.locator('[data-action="upload"]').click();
 if(!(await page.locator('#gs-upload-state').innerText()).includes('65%'))throw Error('Queue state missing');
 await page.locator('[data-action="failure"]').click();
 await page.locator('[data-page="lab"]').first().click();
 await page.locator('[data-action="compare"]').click();
 if(!(await page.locator('#gs-lab-state').innerText()).includes('No benchmark'))throw Error('Lab honesty');
 await page.locator('[data-page="company"]').first().click();
 await page.locator('[data-action="research"]').click();
 fs.mkdirSync('design/previews',{recursive:true});
 await page.screenshot({path:'design/previews/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:1000});
 await page.locator('[data-page="review"]').first().click();
 await page.screenshot({path:'design/previews/mobile.png',fullPage:true});
 const over=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(over)throw Error('Mobile horizontal overflow');
 if(errors.length)throw Error(errors.join(';'));
 console.log(JSON.stringify({flows:9,jsErrors:errors,mobileOverflow:over,desktop:1280,mobile:390}));
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
